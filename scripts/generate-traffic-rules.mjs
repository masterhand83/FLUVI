// Run from any directory: node scripts/generate-traffic-rules.mjs
// Evaluate the classic script so duplicate object keys use JavaScript's last value.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { runInNewContext } from 'node:vm';

const root = new URL('../', import.meta.url);
const source = readFileSync(new URL('apps/v1/src/js/core/reglas.js', root), 'utf8');
const rules = runInNewContext(`${source}\nreglas;`);
const entries = Object.entries(rules).sort(([a], [b]) => a.localeCompare(b));
writeFileSync(new URL('crates/ca-core/tests/fixtures/traffic-rules.csv', root),
    'upstream,center,downstream,result\n' +
    entries.map(([key, value]) => `${key},${value}\n`).join(''));
const table = Array(512).fill('None');
for (const [key, value] of entries) {
    const [left, center, right] = key.split(',').map(Number);
    table[left * 64 + center * 8 + right] = `Some(${value})`;
}
const rows = Array.from({ length: 64 }, (_, row) =>
    `    ${table.slice(row * 8, row * 8 + 8).join(', ')},`);
writeFileSync(new URL('crates/ca-core/src/traffic_rules.rs', root),
    '// Generated by scripts/generate-traffic-rules.mjs. Do not edit.\n' +
    '#[rustfmt::skip]\n' +
    `pub(super) const RULES: [Option<u8>; 512] = [\n${rows.join('\n')}\n];\n`);
console.log(`Evaluated ${entries.length} rules from ${fileURLToPath(root)}apps/v1/src/js/core/reglas.js`);

// Use the real ordinary-street functions, without DOM startup or parking/links.
const traffic = readFileSync(new URL('apps/v1/src/js/core/trafico.js', root), 'utf8');
function functionSource(name) {
    const start = traffic.indexOf(`function ${name}(`);
    if (start < 0) throw new Error(`Missing v1 function: ${name}`);
    const end = traffic.indexOf('\n}', start);
    if (end < 0) throw new Error(`Missing v1 function end: ${name}`);
    return traffic.slice(start, end + 2);
}
const functions = [
    'getLaneDirection', 'getLaneEntryCell', 'getLaneExitCell',
    'generarCelulas', 'actualizarCalle',
].map(functionSource).join('\n');
const trajectories = ['seed,tick,cells'];
for (const seed of [42, 43]) {
    let state = BigInt(seed);
    const math = Object.create(Math);
    math.random = () => {
        state = BigInt.asUintN(64, state + 0x9e3779b97f4a7c15n);
        let z = state;
        z = BigInt.asUintN(64, (z ^ (z >> 30n)) * 0xbf58476d1ce4e5b9n);
        z = BigInt.asUintN(64, (z ^ (z >> 27n)) * 0x94d049bb133111ebn);
        return Number((z ^ (z >> 31n)) >> 11n) / 2 ** 53;
    };
    const states = runInNewContext(`
        ${source}
        const TIPOS = { GENERADOR: 'generador', DEVORADOR: 'devorador' };
        const generacionGlobal = { activa: false };
        function tieneConexionSalida() { return false; }
        ${functions}
        const calle = {
            tipo: 'generador', carriles: 2, tamano: 8,
            probabilidadGeneracion: 0.45, laneDirections: [1, -1],
            arreglo: [Array(8).fill(0), Array(8).fill(0)],
            celulasEsperando: [Array(8).fill(false), Array(8).fill(false)]
        };
        Array.from({ length: 20 }, () => {
            generarCelulas(calle);
            actualizarCalle(calle, 0);
            return calle.arreglo.flat().join('');
        });
    `, { Math: math, window: {} });
    states.forEach((cells, tick) => trajectories.push(`${seed},${tick + 1},${cells}`));
}
writeFileSync(new URL('crates/ca-core/tests/fixtures/traffic-trajectory.csv', root),
    trajectories.join('\n') + '\n');
