import { mkdir, readFile, writeFile } from "node:fs/promises"
import { dirname, resolve } from "node:path"
import { fileURLToPath } from "node:url"

export const LOCALE_LANGUAGES = ["es", "en"]
export const LOCALE_NAMESPACES = ["translation"]
export const FALLBACK_LANGUAGE = "es"

const rootDir = fileURLToPath(new URL("../", import.meta.url))

export function localeCatalogPath(language, namespace = "translation") {
	return resolve(rootDir, "src/locales", language, `${namespace}.json`)
}

export function localeCatalogModulePath() {
	return resolve(rootDir, "src/locales/catalogs.js")
}

export async function readLocaleCatalogs() {
	const catalogs = {}
	for (const language of LOCALE_LANGUAGES) {
		catalogs[language] = {}
		for (const namespace of LOCALE_NAMESPACES) {
			const path = localeCatalogPath(language, namespace)
			const raw = await readFile(path, "utf8")
			try {
				catalogs[language][namespace] = JSON.parse(raw)
			} catch (error) {
				throw new Error(`Invalid JSON in ${path}: ${error.message}`)
			}
		}
	}
	return catalogs
}

export function renderLocaleCatalogModule(catalogs) {
	const body = `${JSON.stringify(catalogs, null, "\t")}\n`
	return [
		"/* Generated by scripts/build-locales.mjs from src/locales/{es,en}/translation.json.",
		" * Do not edit this file by hand. Run `pnpm --filter v1 locales:build`.",
		" */",
		`window.FLUVI_SUPPORTED_LANGUAGES = Object.freeze(${JSON.stringify(LOCALE_LANGUAGES)});`,
		`window.FLUVI_FALLBACK_LANGUAGE = ${JSON.stringify(FALLBACK_LANGUAGE)};`,
		`window.FLUVI_LOCALE_RESOURCES = ${body.trimEnd()};`,
		"",
	].join("\n")
}

export async function buildLocaleCatalogs({ check = false } = {}) {
	const catalogs = await readLocaleCatalogs()
	const output = renderLocaleCatalogModule(catalogs)
	const outputPath = localeCatalogModulePath()
	let current = null
	try {
		current = await readFile(outputPath, "utf8")
	} catch {
		current = null
	}
	if (check) {
		if (current !== output) {
			throw new Error(
				"src/locales/catalogs.js is out of date. Run `pnpm --filter v1 locales:build`.",
			)
		}
		return { outputPath, changed: false }
	}
	if (current !== output) {
		await mkdir(dirname(outputPath), { recursive: true })
		await writeFile(outputPath, output)
	}
	return { outputPath, changed: current !== output }
}

if (
	process.argv[1] &&
	resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
	const result = await buildLocaleCatalogs()
	console.log(
		result.changed
			? `Locale catalogs written to ${result.outputPath}`
			: "Locale catalogs are up to date",
	)
}
